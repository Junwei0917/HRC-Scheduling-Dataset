"""Regenerate the instance files from the frozen configurations in configs/.

With --verify-against the script compares the regenerated bytes with the
published files and writes nothing:

    python -B scripts/generate.py --all --verify-against .

With --output the regenerated files are written to that directory instead:

    python -B scripts/generate.py --all --output regenerated
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[0]))
from hrc_bench.generators import generate_raw
from hrc_bench.io import json_bytes, load_instance, public_instance


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, action="append")
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--verify-against", type=Path)
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    if args.all:
        configs = sorted((root / "configs").glob("*.json"))
    elif args.config:
        configs = args.config
    else:
        parser.error("Specify --config or --all")
    if not args.output and not args.verify_against:
        parser.error("Specify --output or --verify-against")

    count = 0
    for path in configs:
        config = load_instance(path)
        for spec in config["instances"]:
            encoded = json_bytes(public_instance(generate_raw(spec), spec))
            rel = Path("instances") / spec["collection"] / (spec["instance_id"] + ".json")
            if args.verify_against:
                assert (args.verify_against / rel).read_bytes() == encoded, f"mismatch: {rel}"
            if args.output:
                target = args.output / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(encoded)
            count += 1

    if args.verify_against:
        print(f"Verified {count} instances; regenerated bytes match the published files")
    if args.output:
        print(f"Wrote {count} instances to {args.output}")


if __name__ == "__main__":
    main()
